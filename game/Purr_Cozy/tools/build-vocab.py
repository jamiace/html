"""tools/vocab.json (the full 國小～高中 word list) -> js/vocab.js + i18n/vocab.json

    python tools/build-vocab.py            (then run Update-Game.cmd)

tools/vocab.json is the source of truth: one record per word with translations (zh-TW / zh-CN / ja),
parts of speech, KK phonetics, grade, CEEC level and the Purr Cozy fields (stable index, adaptive tier,
accepted spellings, renamed headwords). Never reorder indices: new words must get the next free index,
because saves and the adaptive model refer to words by headword and recent words by index.
Standard library only."""
from pathlib import Path
import json, hashlib, sys
ROOT = Path(__file__).resolve().parent.parent
src = ROOT / 'tools' / 'vocab.json'
D = json.loads(src.read_text(encoding='utf-8-sig'))
words = sorted(D['words'], key=lambda u: u['purr_cozy']['index'])
idx = [u['purr_cozy']['index'] for u in words]
if idx != list(range(len(words))): sys.exit('ERROR: purr_cozy.index must be 0..N-1 without gaps or duplicates.')
seen = set()
for u in words:
    if u['word'] in seen: sys.exit('ERROR: duplicate headword ' + u['word'])
    seen.add(u['word'])
    tr = u['translations']
    for lang in ('zh-TW', 'zh-CN', 'ja'):
        if not tr.get(lang): sys.exit(f'ERROR: {u["word"]} has no {lang} translation')
meanings, runtime, vocab, entries = {}, {}, [], []
for u in words:
    tr = u['translations']; text = tr['zh-TW'] + '\u0001' + tr['zh-CN'] + '\u0001' + tr['ja']
    key = 'v_' + hashlib.sha1(text.encode('utf-8')).hexdigest()[:12]   # words with identical meanings share one key
    meanings[key] = {'zh-TW': tr['zh-TW'], 'zh-CN': tr['zh-CN'], 'ja': tr['ja']}
    runtime[u['word']] = key
    pc = u['purr_cozy']
    v = {'w': u['word'], 'p': '/'.join(u['pos']) or 'n.', 'ph': u['phonetic']['kk'] or '', 't': pc['level'], 'au': pc['audio'], 'g': u['grade_num'], 'd': pc['adaptive_tier']}
    if pc.get('accept'): v['a'] = pc['accept']
    vocab.append(v)
    entries.append({'word': u['word'], 'phonetic': v['ph'], 'partOfSpeech': v['p'], 'level': pc['level'], 'grade': u['grade_num'], 'audio': pc['audio'], 'meaningKey': key})
renamed = {u['purr_cozy']['old_word']: u['word'] for u in words if u['purr_cozy'].get('old_word')}
vj = {'schema': 2, 'defaultLanguage': 'zh-TW', 'languages': ['zh-TW', 'zh-CN', 'ja'], 'meanings': meanings, 'runtime': runtime, 'entries': entries}
(ROOT / 'i18n' / 'vocab.json').write_text(json.dumps(vj, ensure_ascii=False, indent=2), encoding='utf-8')
js = ('/* Word metadata and stable indices. Meanings live in i18n/vocab.json. Generated by tools/build-vocab.py from tools/vocab.json.\n'
      '   w word · p parts of speech · ph KK phonetics · t Level 1-6 (CEEC level; the 108 curriculum basic 1200 words are L1, the other 800 at most L2)\n'
      '   g estimated school grade 1-12 · d adaptive difficulty on the Level scale (finer below Level 2) · a accepted spelling variants\n'
      '   Indices are stable: new words are only ever appended. */\n'
      'const VOCAB = ' + json.dumps(vocab, ensure_ascii=False, separators=(', ', ': ')) + ';\n'
      'const VPOS_RE=/\\b(n|v|adj|adv|prep|conj|pron|art|num|interj|aux|det|abbr|phr)\\./g;\n'
      'VOCAB.forEach((v,i)=>{v.i=i;v.ps=(v.p.match(VPOS_RE)||[]).map(s=>s.slice(0,-1));if(!v.ps.length)v.ps=["n"];if(v.d==null)v.d=v.t;Object.defineProperty(v,"z",{enumerable:true,get(){return I18n.meaning(v.w)}})});\n'
      'const VIDX=Object.fromEntries(VOCAB.map(v=>[v.w,v.i]));\n'
      'const VLEVELS=[...new Set(VOCAB.map(v=>v.t))].sort((a,b)=>a-b);\n'
      'const TIER_NAME=new Proxy({},{get:(_,k)=>"Level "+String(k)});\n'
      '// headwords renamed in 0.92.45 (old saves keep progress under the old key until Learn.migrate moves it)\n'
      'const VOCAB_RENAMED=' + json.dumps(renamed, ensure_ascii=False) + ';\n')
(ROOT / 'js' / 'vocab.js').write_text(js, encoding='utf-8')
print('READY:', len(vocab), 'words,', len(meanings), 'meanings. Now run Update-Game.cmd.')
